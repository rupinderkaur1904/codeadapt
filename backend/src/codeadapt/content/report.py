"""Markdown discrimination report for one problem (`codeadapt-content report`).

Deterministic: the same content measured in the same environment renders byte-identical
text (no timestamps, fixed ordering), so a report diff shows a real change.

Reports contain hidden tests and error-model descriptions. For private content, write
them to the private content repository, never to the public one (ADR-009).
"""

from __future__ import annotations

from codeadapt.content.fingerprint import FingerprintSet
from codeadapt.content.loader import LoadedProblem
from codeadapt.content.validate import ValidationReport


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", "/")


def render_report(problem: LoadedProblem, fps: FingerprintSet, report: ValidationReport) -> str:
    spec = problem.spec
    env = fps.environment
    models = list(fps.models)
    ref = fps.reference.tests
    lines = [
        f"# Discrimination report: `{spec.slug}`",
        "",
        "Generated by `codeadapt-content report` from executed fingerprints. Do not edit by "
        "hand; regenerate it.",
        "",
        f"* Content version: `{problem.version}`",
        f"* Environment: {env.compiler_version}, `{env.container_runtime}`, image `{env.image}`",
        f"* Runs per test: {fps.repeats}",
        f"* Result: {'valid' if report.ok else 'INVALID'} "
        f"({len(report.errors)} errors, {len(report.warnings)} warnings, "
        f"{len(report.limitations)} documented limitations)",
        "",
        "## Matrix",
        "",
        "Each cell is the program's observed behaviour; `·` means identical to the reference.",
        "",
        "| Test | Reference | " + " | ".join(f"`{m}`" for m in models) + " |",
        "| --- | --- | " + " | ".join("---" for _ in models) + " |",
    ]
    for test in spec.tests:
        r = ref.get(test.key)
        r_sig = r.signature if r else None
        cells = []
        for m in models:
            t = fps.models[m].tests.get(test.key)
            if t is None:
                cells.append("n/a")
            elif t.signature is None:
                cells.append("NONDET")
            elif t.signature == r_sig:
                cells.append("·")
            else:
                cells.append(_cell(str(t.signature)))
        lines.append(
            f"| `{test.key}` | {_cell(str(r_sig)) if r_sig else 'NONDET'} | "
            + " | ".join(cells)
            + " |"
        )

    limitation = {m.key: m.known_limitation for m in spec.error_models}
    lines += [
        "",
        "## Error models",
        "",
        "| Model | Skill | Detecting tests | Behaviour groups | Documented limitation |",
        "| --- | --- | --- | --- | --- |",
        *(
            f"| `{m.key}` | {m.skill} | {len(m.detecting_tests)} | {m.behaviour_groups} | "
            f"{_cell(limitation.get(m.key) or '—')} |"
            for m in report.models
        ),
        "",
        "## Behaviour groups",
        "",
        "Tests that every modelled program passes together or fails together. Evidence "
        "strength is counted in groups, not tests. Groups are relative to the modelled "
        "programs: a new model can split one.",
        "",
        "| Group | Tests | Detected models |",
        "| --- | --- | --- |",
        *(
            f"| {i} | {', '.join(f'`{t}`' for t in g.tests)} | "
            f"{', '.join(f'`{m}`' for m in g.detected_models) or 'none'} |"
            for i, g in enumerate(report.groups, start=1)
        ),
        "",
        "## Pairwise separation",
        "",
        "| Pair | Distinguishing tests |",
        "| --- | --- |",
        *(f"| `{p.a}` / `{p.b}` | {len(p.distinguishing_tests)} |" for p in report.pairs),
        "",
        "## Declared intent versus measurement",
        "",
        "| Test | Purpose | Declared `distinguishes` | Measured | Agree |",
        "| --- | --- | --- | --- | --- |",
    ]
    measured = {t: g.detected_models for g in report.groups for t in g.tests}
    for test in spec.tests:
        got = measured.get(test.key, ())
        declared = test.distinguishes
        agree = (
            "undeclared" if declared is None else "yes" if sorted(declared) == list(got) else "NO"
        )
        lines.append(
            f"| `{test.key}` | {_cell(test.purpose or '—')} | "
            f"{'—' if declared is None else ', '.join(sorted(declared)) or 'none'} | "
            f"{', '.join(got) or 'none'} | {agree} |"
        )

    def section(title: str, items: tuple[str, ...]) -> list[str]:
        return ["", f"## {title}", "", *([f"* {_cell(i)}" for i in items] or ["None."])]

    lines += section("Errors", report.errors)
    lines += section("Warnings", report.warnings)
    lines += section("Documented limitations", report.limitations)
    return "\n".join(lines) + "\n"
