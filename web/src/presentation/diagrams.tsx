// Places the column of cases linked to the primary actor on a circle around the point where
// the actor's lines start. Each line then meets its ellipse at the nearest end and clears
// every ellipse between it and the actor.
function arc<T extends { x: number; y: number; w?: number }>(
  cases: T[],
  column: number,
  origin: [number, number],
  radius: number,
): T[] {
  const [ox, oy] = origin;
  return cases.map((c) => {
    if (c.x !== column) return c;
    const dy = c.y - oy;
    return { ...c, x: ox + Math.sqrt(radius * radius - dy * dy) + (c.w ?? 190) / 2 };
  });
}

